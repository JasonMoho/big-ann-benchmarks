#!/usr/bin/env python3
"""
Test script for dynamic workload generation and evaluation using direct function calls.
This script:
  A) Generates a workload by directly calling DynamicWorkloadGenerator.
  B) Evaluates the workload by directly calling WorkloadRunner.run_task.
  C) Uses the "faiss-ivf" index for evaluation (via the index factory).
"""

import os
import yaml
import time

# Import the workload generator and evaluator components.
from neurips23.runbooks.workload_gen_and_eval.workload_generator import (
    load_yaml_config,
    DynamicWorkloadGenerator,
    logger
)
from neurips23.runbooks.workload_gen_and_eval.workload_evaluator import WorkloadRunner, select_index

def write_yaml(filepath, data):
    with open(filepath, "w") as f:
        yaml.dump(data, f)

def main():
    # Create a temporary directory for the test workload.
    # temp_dir = tempfile.mkdtemp(prefix="test_workload_")
    # print("Temporary test workload directory:", temp_dir)
    temp_dir = "test_workload"
    os.makedirs(temp_dir, exist_ok=True)

    # --- Step A: Run the Workload Generator ---

    # Define a generator configuration dictionary.
    gen_config = {
        "dataset": "random-2d",
        "workload_dir": os.path.join(temp_dir, "workload"),
        "metric": "l2",
        "insert_ratio": 0.5,
        "delete_ratio": 0.25,
        "query_ratio": 0.25,
        "update_batch_size": 100,
        "query_batch_size": 10,
        "num_operations": 100,
        "initial_size": 1000,
        "cluster_size": 10,
        "update_sample_distribution": "uniform",
        "query_sample_distribution": "uniform",
        "seed": 1738
    }

    # Write generator configuration to a YAML file (for reference).
    gen_config_path = os.path.join(temp_dir, "gen_config.yaml")
    write_yaml(gen_config_path, gen_config)

    print("Starting workload generation directly...")
    # Directly instantiate the generator using the config values.
    generator = DynamicWorkloadGenerator(
        dataset=gen_config.get("dataset"),
        workload_dir=gen_config.get("workload_dir"),
        metric=gen_config.get("metric"),
        insert_ratio=gen_config.get("insert_ratio"),
        delete_ratio=gen_config.get("delete_ratio"),
        query_ratio=gen_config.get("query_ratio"),
        update_batch_size=gen_config.get("update_batch_size"),
        query_batch_size=gen_config.get("query_batch_size"),
        num_operations=gen_config.get("num_operations"),
        initial_size=gen_config.get("initial_size"),
        cluster_size=gen_config.get("cluster_size"),
        update_sample_distribution=gen_config.get("update_sample_distribution"),
        query_sample_distribution=gen_config.get("query_sample_distribution"),
        seed=gen_config.get("seed"),
    )
    start_gen = time.time()
    generator.generate_workload()
    elapsed_gen = time.time() - start_gen
    print(f"Workload generation completed in {elapsed_gen:.2f} seconds.")

    # --- Step B: Run the Workload Evaluator ---

    # Define the evaluator configuration dictionary.
    # Notice that we point to the runbook generated by the generator.
    workload_dir = gen_config.get("workload_dir")
    eval_config = {
        "workload_dir": workload_dir,
        "distance": "l2",
        "k": 10,
        "run_count": 1,
        "search_type": "knn",
        # The generator saved the runbook as JSON (JSON is valid YAML).
        "runbook_file": os.path.join(workload_dir, "runbook.json"),
        "indexes": [
            {
                "index_name": "faiss-ivf",
                "search_params": {}
            },
            {
                "index_name": "faiss-flat",
            }
        ],
        "results_dir": os.path.join(temp_dir, "results")
    }

    # Write evaluator configuration for reference.
    eval_config_path = os.path.join(temp_dir, "eval_config.yaml")
    write_yaml(eval_config_path, eval_config)

    print("Starting workload evaluation directly...")

    # Load evaluator configuration from the YAML file.
    with open(eval_config_path, "r") as f:
        econfig = yaml.safe_load(f)

    workload_dir = econfig.get("workload_dir")
    distance = econfig.get("distance", "l2")
    k = econfig.get("k", 10)
    run_count = econfig.get("run_count", 1)
    search_type = econfig.get("search_type", "knn")
    runbook_file = econfig.get("runbook_file")
    results_dir = econfig.get("results_dir", os.path.join(temp_dir, "results"))
    indexes = econfig.get("indexes", [])

    # Load the runbook using YAML (it can parse JSON).
    with open(runbook_file, "r") as f:
        runbook = yaml.safe_load(f)

    # Process each index configuration by directly calling the evaluation functions.
    for index_conf in indexes:
        index_name = index_conf.get("index_name", "default_index")
        build_params = index_conf.get("build_params", {})
        search_params = index_conf.get("search_params", {})

        print(f"=== Evaluating index: {index_name} ===")
        # Select the index via the index factory.
        algo = select_index(index_name)
        build_time = WorkloadRunner.build(algo, workload_dir, build_params)
        print(f"Build time for index '{index_name}': {build_time:.4f} seconds.")
        attrs, best_results = WorkloadRunner.run_task(
            algo, workload_dir, distance, k, run_count, search_type,
            runbook, search_params, results_dir=results_dir
        )
        print(f"Results for index '{index_name}':")
        print(attrs)
        print("Best search results obtained (saved in the results directory).")
        print("=======================================")

    print("Workload evaluation completed.")

if __name__ == "__main__":
    main()