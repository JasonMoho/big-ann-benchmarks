def compute_recall(pred_ids: np.ndarray, gt_ids: np.ndarray) -> float:
    """
    Compute average recall over queries.

    For each query, recall is defined as:
      recall = (# of common elements between predicted and ground truth) / k
    The final recall is averaged over all queries.

    Parameters:
        pred_ids: Predicted neighbor IDs (n_queries x k).
        gt_ids: Ground truth neighbor IDs (n_queries x k).

    Returns:
        The average recall value.
    """
    n_queries, k = gt_ids.shape
    recalls = []
    for i in range(n_queries):
        inter = np.intersect1d(pred_ids[i], gt_ids[i])
        recalls.append(len(inter) / k)
    return float(np.mean(recalls))


class StreamingRunner:
    """
    Processes operations defined in a runbook using a provided or default index.

    This evaluator:
      - Loads necessary configuration and vector data.
      - Loads a runbook (YAML) generated by the workload generator.
      - Builds an index from the initial resident set if no external index is provided.
      - Loads precomputed ground truth from a file.
      - Processes each operation (insert or query) and computes recall for query operations.

    Ground truth must be precomputed and stored in 'gt_ids.npy' in the workload directory.
    """

    def __init__(self,
                 workload_dir: Path,
                 metric: str = DEFAULT_METRIC,
                 k: int = DEFAULT_K,
                 use_gpu: bool = DEFAULT_USE_GPU,
                 use_precomputed_gt: bool = DEFAULT_USE_PRECOMPUTED_GT,
                 external_index: Optional[Any] = None) -> None:
        self.workload_dir = workload_dir
        self.metric = metric.lower()
        self.k = k
        self.use_gpu = use_gpu
        self.use_precomputed_gt = use_precomputed_gt
        self.external_index = external_index

        # Load dataset vectors
        self.base_vectors = np.load(self.workload_dir / "base_vectors.npy")
        query_file = self.workload_dir / "query_vectors.npy"
        self.queries = np.load(query_file) if query_file.exists() else self.base_vectors
        self.initial_indices = np.load(self.workload_dir / "initial_indices.npy")
        self.operations_dir = self.workload_dir / "operations"
        self.runbook: Dict[str, Any] = {}
        self.index = None  # The index used for evaluation

    def load_runbook(self) -> None:
        """
        Load the runbook generated by the workload generator.

        The runbook must be present as 'runbook.yaml' in the workload directory.
        """
        runbook_file = self.workload_dir / "runbook.yaml"
        if not runbook_file.exists():
            logger.error("Runbook file '%s' does not exist.", runbook_file)
            raise FileNotFoundError(f"Runbook file '{runbook_file}' not found.")
        with runbook_file.open("r") as f:
            self.runbook = yaml.safe_load(f)
        total_ops = len(self.runbook.get("operations", {}))
        logger.info("Loaded runbook with %d operations.", total_ops)

    def build_initial_index(self) -> None:
        """
        Build a default Faiss index from the initial resident set, unless an external index is provided.
        """
        if self.external_index is not None:
            self.index = self.external_index
            logger.info("Using externally provided index.")
        else:
            initial_vectors = self.base_vectors[self.initial_indices]
            self.index = build_faiss_index(initial_vectors, self.metric, self.use_gpu)

    def load_ground_truth(self) -> Tuple[np.ndarray, float]:
        """
        Load precomputed ground truth from a file.

        Returns:
            A tuple of (gt_ids, load_time). The ground truth file is expected to be 'gt_ids.npy'.

        Raises:
            FileNotFoundError: If the precomputed ground truth file is not found.
        """
        gt_file = self.workload_dir / "gt_ids.npy"
        if self.use_precomputed_gt and gt_file.exists():
            t0 = time.time()
            gt_ids = np.load(gt_file)
            load_time = time.time() - t0
            logger.info("Loaded precomputed ground truth in %.4fs.", load_time)
            return gt_ids, load_time
        else:
            error_msg = ("Ground truth file 'gt_ids.npy' not found in the workload directory. "
                         "Ensure that ground truth is generated externally (e.g., by the workload generator).")
            logger.error(error_msg)
            raise FileNotFoundError(error_msg)

    def process_operation(self, op_key: str, op_entry: Dict[str, Any], gt_ids: np.ndarray) -> None:
        """
        Process a single operation from the runbook.

        For insert operations, new vectors are added to the index.
        For query operations, the index is queried and recall is computed using the precomputed ground truth.
        Delete operations are logged as unsupported.

        Parameters:
            op_key: The operation identifier.
            op_entry: Operation details from the runbook.
            gt_ids: Precomputed ground truth neighbor IDs.
        """
        op_file = self.operations_dir / f"{op_key}.npy"
        op_type = op_entry["operation"]
        logger.info("Processing op %s: %s", op_key, op_type)
        start = time.time()

        if op_type == "insert":
            try:
                new_ids = np.load(op_file)
                new_vectors = self.base_vectors[new_ids]
                self.index.add(new_vectors)
                logger.info("Inserted %d vectors.", new_ids.size)
            except Exception as e:
                logger.error("Error during insert op %s: %s", op_key, e)
                return

        elif op_type == "delete":
            logger.info("Delete op encountered; deletion is unsupported. Skipping op %s.", op_key)

        elif op_type == "query":
            try:
                q_indices = np.load(op_file)
            except Exception as e:
                logger.error("Error loading query indices for op %s: %s", op_key, e)
                return
            queries = self.queries[q_indices]
            t0 = time.time()
            try:
                distances, pred_ids = self.index.search(queries, self.k)
            except Exception as e:
                logger.error("Error during search op %s: %s", op_key, e)
                return
            q_time = time.time() - t0
            op_entry["query_time"] = q_time
            try:
                gt_for_op = gt_ids[q_indices]
            except Exception as e:
                logger.error("Error retrieving ground truth for op %s: %s", op_key, e)
                return
            recall = compute_recall(pred_ids, gt_for_op)
            op_entry["recall"] = recall
            try:
                np.save(self.operations_dir / f"{op_key}_pred_ids.npy", pred_ids)
            except Exception as e:
                logger.error("Failed to save prediction results for op %s: %s", op_key, e)
            logger.info("Query op %s: processed %d queries in %.4fs, recall=%.4f",
                        op_key, queries.shape[0], q_time, recall)
        else:
            logger.warning("Unknown operation type '%s' encountered in op %s.", op_type, op_key)
        op_entry["latency"] = time.time() - start

    def run(self) -> None:
        """
        Run the evaluation over all operations defined in the runbook.

        This method loads the runbook and precomputed ground truth, builds the index,
        and processes each operation, updating the runbook with evaluation metrics.
        """
        self.load_runbook()
        self.build_initial_index()
        gt_ids, load_time = self.load_ground_truth()

        operations = self.runbook.get("operations", {})
        op_keys = sorted(operations.keys(), key=lambda x: int(x))
        for op_key in op_keys:
            op_entry = operations[op_key]
            self.process_operation(op_key, op_entry, gt_ids)
            logger.info("Op %s: %s, latency=%.4fs, n_resident=%s, recall=%s",
                        op_key,
                        op_entry.get("operation", "N/A"),
                        op_entry.get("latency", 0),
                        op_entry.get("n_resident", "N/A"),
                        op_entry.get("recall", "N/A"))
        self.runbook["evaluation"] = {"gt_load_time": load_time}
        try:
            idx_size = self.index.ntotal
        except AttributeError:
            idx_size = getattr(self.index, "get_index_size", lambda: "N/A")()
        logger.info("Evaluation complete. Final index size: %s", idx_size)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Evaluate streaming workload using a provided index and precomputed ground truth."
    )
    parser.add_argument("--config", type=str, required=True,
                        help="Path to evaluation YAML config file.")
    parser.add_argument("--index_file", type=str,
                        help="Optional path to a serialized external index (pickle format).",
                        default=None)
    args = parser.parse_args()

    config = load_yaml_config(Path(args.config))
    workload_dir = Path(config["workload_dir"])
    metric = config.get("metric", DEFAULT_METRIC)
    k = config.get("k", DEFAULT_K)
    use_gpu = config.get("use_gpu", DEFAULT_USE_GPU)
    use_precomputed_gt = config.get("use_precomputed_gt", DEFAULT_USE_PRECOMPUTED_GT)

    external_index = None
    if args.index_file:
        try:
            with open(args.index_file, "rb") as f:
                external_index = pickle.load(f)
            logger.info("Loaded external index from %s", args.index_file)
        except Exception as e:
            logger.error("Failed to load external index from %s: %s", args.index_file, e)

    runner = StreamingRunner(
        workload_dir=workload_dir,
        metric=metric,
        k=k,
        use_gpu=use_gpu,
        use_precomputed_gt=use_precomputed_gt,
        external_index=external_index
    )

    logger.info("Starting evaluation using workload directory: %s", workload_dir)
    start = time.time()
    try:
        runner.run()
    except Exception as e:
        logger.error("Evaluation failed: %s", e)
    elapsed = time.time() - start
    logger.info("Total evaluation time: %.2fs", elapsed)


if __name__ == "__main__":
    main()