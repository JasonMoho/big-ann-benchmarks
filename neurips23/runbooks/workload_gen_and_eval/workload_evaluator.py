#!/usr/bin/env python3
"""
Streaming Workload Evaluator Using Faiss for Ground Truth & Recall Computation

This module implements a StreamingRunner that loads a runbook (YAML format) generated by the
workload generator and processes its operations using a provided index. It supports any index
that implements a "search(query, k)" method. If an external index is not supplied, the runner builds
a default Faiss Flat index from the initial resident set. Ground truth is loaded exclusively from
a precomputed file; the evaluator does not generate ground truth.

Usage:
  python neurips23/streaming/workload_evaluator.py --config eval_config.yaml [--index_file path/to/index.pkl]

The evaluation configuration YAML must include:
  workload_dir: Directory containing workload files and runbook.
  metric: "l2" or "ip".
  k: Number of nearest neighbors for queries.
  use_gpu: true/false (for indexing).
  use_precomputed_gt: true/false.
"""

import argparse
import logging
import pickle
import time
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import numpy as np
import faiss
import yaml

# === Default Constants ===
DEFAULT_METRIC = "l2"
DEFAULT_K = 10
DEFAULT_USE_GPU = False
DEFAULT_USE_PRECOMPUTED_GT = True

logger = logging.getLogger("WorkloadEvaluator")
logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")


def load_yaml_config(config_path: Path) -> Dict[str, Any]:
    """Load the YAML configuration from the specified file."""
    with config_path.open("r") as f:
        return yaml.safe_load(f)
