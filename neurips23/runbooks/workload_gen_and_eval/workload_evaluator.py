#!/usr/bin/env python3
"""
Streaming Runner Using Faiss for Ground Truth & Recall Computation

This module implements a StreamingRunner that loads a runbook (YAML format)
generated by the workload generator and processes its operations using a provided index.
It supports any index that implements a "search(query, k)" method.
An external index may be provided via a command‑line parameter; otherwise, the runner
builds a default Faiss Flat index from the initial resident set.
Ground truth is computed (or loaded if precomputed) using Faiss over the entire base dataset,
and query recall is computed by comparing test results with the ground truth.

Usage:
  python neurips23/streaming/workload_evaluator.py --config eval_config.yaml [--index_file path/to/index.pkl]

The YAML configuration for evaluation must include:
  workload_dir: directory containing workload files and runbook
  metric: "l2" or "ip"
  k: number of nearest neighbors for queries
  use_gpu: true/false (for GT computation)
  use_precomputed_gt: true/false
"""

import argparse
import logging
import pickle
import time
from pathlib import Path
from typing import Any, Dict

import numpy as np
import faiss
import yaml

# === Default Constants ===
DEFAULT_METRIC = "l2"
DEFAULT_K = 10
DEFAULT_USE_GPU = False
DEFAULT_USE_PRECOMPUTED_GT = True

logging.basicConfig(level=logging.INFO, format="%(asctime)s [%(levelname)s] %(message)s")


def load_yaml_config(config_path: Path) -> Dict[str, Any]:
    with config_path.open("r") as f:
        return yaml.safe_load(f)


def compute_recall(pred_ids: np.ndarray, gt_ids: np.ndarray) -> float:
    """
    Computes average recall over queries:
      recall = (size of intersection / k) averaged over all queries.
    """
    n_queries, k = gt_ids.shape
    recalls = []
    for i in range(n_queries):
        inter = np.intersect1d(pred_ids[i], gt_ids[i])
        recalls.append(len(inter) / k)
    return float(np.mean(recalls))


class StreamingRunner:
    """
    Loads the runbook and processes its operations using a provided index.

    An external index can be supplied (via --index_file); if none is provided, a default
    Faiss Flat index is built using the initial resident set.

    Ground truth for all queries is computed using Faiss on the entire base dataset (or loaded),
    and each query op's recall is computed.
    """

    def __init__(self, workload_dir: Path, metric: str = DEFAULT_METRIC,
                 k: int = DEFAULT_K, use_gpu: bool = DEFAULT_USE_GPU,
                 use_precomputed_gt: bool = DEFAULT_USE_PRECOMPUTED_GT,
                 external_index: Any = None) -> None:
        self.workload_dir = workload_dir
        self.metric = metric.lower()
        self.k = k
        self.use_gpu = use_gpu
        self.use_precomputed_gt = use_precomputed_gt
        self.external_index = external_index
        self.runbook: Dict[str, Any] = {}
        self.operations_dir = self.workload_dir / "operations"
        self.base_vectors = np.load(self.workload_dir / "base_vectors.npy")
        query_file = self.workload_dir / "query_vectors.npy"
        self.queries = np.load(query_file) if query_file.exists() else self.base_vectors
        self.initial_indices = np.load(self.workload_dir / "initial_indices.npy")
        self.index = None  # The test index

    def load_runbook(self) -> None:
        runbook_file = self.workload_dir / "runbook.yaml"
        with runbook_file.open("r") as f:
            self.runbook = yaml.safe_load(f)
        logging.info("Loaded runbook with %d operations.", len(self.runbook.get("operations", {})))

    def build_initial_index(self) -> None:
        """
        If an external index is provided, it is used directly.
        Otherwise, a default Faiss Flat index is built from the initial resident set.
        """
        if self.external_index is not None:
            self.index = self.external_index
            logging.info("Using externally provided index.")
        else:
            initial_vectors = self.base_vectors[self.initial_indices]
            d = initial_vectors.shape[1]
            if self.metric == "l2":
                idx_cpu = faiss.IndexFlatL2(d)
            else:
                idx_cpu = faiss.IndexFlatIP(d)
            if self.use_gpu:
                res = faiss.StandardGpuResources()
                idx = faiss.index_cpu_to_gpu(res, 0, idx_cpu)
                logging.info("Using GPU for default index.")
            else:
                idx = idx_cpu
                logging.info("Using CPU for default index.")
            idx.add(initial_vectors)
            self.index = idx
            logging.info("Default index built with %d vectors.", getattr(idx, "ntotal", "N/A"))

    def get_ground_truth(self) -> (np.ndarray, float):
        """
        Computes or loads ground truth for all query vectors using an exhaustive Faiss index on the full base dataset.
        Returns:
            gt_ids (n_queries, GT_K), and GT computation time.
        """
        gt_file = self.workload_dir / "gt_ids.npy"
        d = self.base_vectors.shape[1]
        gt_ids = None
        if self.use_precomputed_gt and gt_file.exists():
            t0 = time.time()
            gt_ids = np.load(gt_file)
            gt_time = time.time() - t0
            logging.info("Loaded precomputed ground truth in %.4fs.", gt_time)
        return gt_ids

    def run(self) -> None:
        """
        Processes each operation in the runbook. For query ops, the test index is queried,
        recall is computed by comparing results with precomputed GT, and timing is recorded.
        """
        self.load_runbook()
        self.build_initial_index()
        gt_ids, gt_time = self.get_ground_truth()

        operations = self.runbook.get("operations", {})
        op_keys = sorted([int(k) for k in operations.keys() if isinstance(k, (str, int))])
        for op_key in op_keys:
            op_entry = operations[str(op_key)]
            op_type = op_entry["operation"]
            logging.info("Processing op %d: %s", op_key, op_type)
            start = time.time()
            op_file = self.operations_dir / f"{op_key}.npy"
            if op_type == "insert":
                new_ids = np.load(op_file)
                new_vectors = self.base_vectors[new_ids]
                self.index.add(new_vectors)
                logging.info("Inserted %d vectors.", new_ids.size)
            elif op_type == "delete":
                logging.info("Delete op encountered; deletion unsupported; skipping.")
            elif op_type == "query":
                q_indices = np.load(op_file)
                queries = self.queries[q_indices]
                t0 = time.time()
                distances, pred_ids = self.index.search(queries, self.k)
                q_time = time.time() - t0
                op_entry["query_time"] = q_time
                # Retrieve corresponding GT rows.
                gt_for_op = gt_ids[q_indices]
                recall = compute_recall(pred_ids, gt_for_op)
                op_entry["recall"] = recall
                np.save(self.operations_dir / f"{op_key}_pred_ids.npy", pred_ids)
                logging.info("Query op: processed %d queries in %.4fs, recall=%.4f",
                             queries.shape[0], q_time, recall)
            else:
                logging.warning("Unknown operation type: %s", op_type)
            op_entry["latency"] = time.time() - start

        self.runbook["evaluation"] = {"gt_time": gt_time}
        try:
            idx_size = self.index.ntotal
        except AttributeError:
            idx_size = self.index.get_index_size() if hasattr(self.index, "get_index_size") else "N/A"
        logging.info("Evaluation complete. Final index size: %s", idx_size)
        for key, entry in operations.items():
            logging.info("Op %s: %s, latency=%.4fs, resident=%s, recall=%s",
                         key, entry.get("operation"), entry.get("latency"),
                         entry.get("n_resident", "N/A"), entry.get("recall", "N/A"))


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate streaming workload using a provided index and Faiss-based ground truth."
    )
    parser.add_argument("--config", type=str, required=True,
                        help="Path to evaluation YAML config file.")
    parser.add_argument("--index_file", type=str,
                        help="Optional path to a serialized external index (pickle format).",
                        default=None)
    args = parser.parse_args()

    config = load_yaml_config(Path(args.config))
    workload_dir = Path(config["workload_dir"])
    metric = config.get("metric", DEFAULT_METRIC)
    k = config.get("k", DEFAULT_K)
    use_gpu = config.get("use_gpu", DEFAULT_USE_GPU)
    use_precomputed_gt = config.get("use_precomputed_gt", DEFAULT_USE_PRECOMPUTED_GT)

    external_index = None
    if args.index_file:
        with open(args.index_file, "rb") as f:
            external_index = pickle.load(f)
        logging.info("Loaded external index from %s", args.index_file)

    runner = StreamingRunner(
        workload_dir=workload_dir,
        metric=metric,
        k=k,
        use_gpu=use_gpu,
        use_precomputed_gt=use_precomputed_gt,
        external_index=external_index
    )
    logging.info("Starting evaluation using workload directory: %s", workload_dir)
    start = time.time()
    runner.run()
    elapsed = time.time() - start
    logging.info("Total evaluation time: %.2fs", elapsed)


if __name__ == "__main__":
    main()